"""topics group: create_topic, delete_topic, get_topic, list_topics, update_topic"""

import logging

from fastmcp import FastMCP
from mcp.types import ToolAnnotations
from pydantic import Field

from .. import service
from ..logging_utils import ToolLogger
from ..schemas.topics import (
    CreateTopicData,
    CreateTopicResult,
    DeleteTopicData,
    DeleteTopicResult,
    GetTopicData,
    GetTopicResult,
    ListTopicsData,
    ListTopicsResult,
    Topic,
    UpdateTopicData,
    UpdateTopicResult,
)
from ._helpers import _err, _handle_request_exc, _upstream_err

logger = logging.getLogger("google-classroom-mcp.tools.topics")


def register_topics_tools(mcp: FastMCP) -> None:

    @mcp.tool(
        name="create_topic",
        description=(
            "Creates a topic in a course and returns it. Topic names are case sensitive and the course may reach "
            "a topic limit."
        ),
        annotations=ToolAnnotations(readOnlyHint=False, destructiveHint=False, openWorldHint=True),
    )
    def create_topic(
        course_id: str = Field(description="Identifier of the course. This identifier can be either the Classroom-assigned identifier or an alias."),
        name: str = Field(description="The name of the topic, generated by the user. Leading and trailing whitespaces, if any, are trimmed. Also, multiple consecutive whitespaces are collapsed into one inside the name. The result must be a non-empty string. Topic names are case sensitive, and must be no longer than 100 characters."),
    ) -> CreateTopicResult:
        tlog = ToolLogger(logger, "create_topic")
        if not course_id.strip():
            return _err(CreateTopicResult, tlog, "VALIDATION_ERROR", "course_id must not be empty", 400)
        body = {k: v for k, v in {"name": name}.items() if v is not None}
        try:
            data, status, retry_after = service.execute(lambda s: s.courses().topics().create(courseId=course_id, body=body))
            if 200 <= status < 300:
                tlog.success()
                return CreateTopicResult(success=True, statusCode=status, data=CreateTopicData(**data))
            return _upstream_err(CreateTopicResult, tlog, status, data, retry_after)
        except Exception as exc:
            return _handle_request_exc(CreateTopicResult, tlog, exc)

    @mcp.tool(
        name="delete_topic",
        description=(
            "DESTRUCTIVE — REQUIRES EXPLICIT USER CONFIRMATION BEFORE CALLING. Permanently deletes a course "
            "topic. This action is irreversible — the topic (coursework and materials filed under it are not "
            "deleted) cannot be recovered. NEVER call this tool autonomously or as part of an automated flow. You "
            "MUST stop, tell the user exactly what will be deleted and that it is permanent, and wait for their "
            "explicit written confirmation before proceeding."
        ),
        annotations=ToolAnnotations(readOnlyHint=False, destructiveHint=True, openWorldHint=True),
    )
    def delete_topic(
        course_id: str = Field(description="Identifier of the course. This identifier can be either the Classroom-assigned identifier or an alias."),
        topic_id: str = Field(description="Identifier of the topic to delete."),
    ) -> DeleteTopicResult:
        tlog = ToolLogger(logger, "delete_topic")
        if not course_id.strip():
            return _err(DeleteTopicResult, tlog, "VALIDATION_ERROR", "course_id must not be empty", 400)
        if not topic_id.strip():
            return _err(DeleteTopicResult, tlog, "VALIDATION_ERROR", "topic_id must not be empty", 400)
        try:
            data, status, retry_after = service.execute(lambda s: s.courses().topics().delete(courseId=course_id, id=topic_id))
            if 200 <= status < 300:
                tlog.success()
                return DeleteTopicResult(success=True, statusCode=status, data=DeleteTopicData(deleted=True, courseId=course_id, id=topic_id))
            return _upstream_err(DeleteTopicResult, tlog, status, data, retry_after)
        except Exception as exc:
            return _handle_request_exc(DeleteTopicResult, tlog, exc)

    @mcp.tool(
        name="get_topic",
        description="Retrieves one topic of a course by ID and returns its name, ID and last update time.",
        annotations=ToolAnnotations(readOnlyHint=True, openWorldHint=True),
    )
    def get_topic(
        course_id: str = Field(description="Identifier of the course."),
        topic_id: str = Field(description="Identifier of the topic."),
    ) -> GetTopicResult:
        tlog = ToolLogger(logger, "get_topic")
        if not course_id.strip():
            return _err(GetTopicResult, tlog, "VALIDATION_ERROR", "course_id must not be empty", 400)
        if not topic_id.strip():
            return _err(GetTopicResult, tlog, "VALIDATION_ERROR", "topic_id must not be empty", 400)
        try:
            data, status, retry_after = service.execute(lambda s: s.courses().topics().get(courseId=course_id, id=topic_id))
            if 200 <= status < 300:
                tlog.success()
                return GetTopicResult(success=True, statusCode=status, data=GetTopicData(**data))
            return _upstream_err(GetTopicResult, tlog, status, data, retry_after)
        except Exception as exc:
            return _handle_request_exc(GetTopicResult, tlog, exc)

    @mcp.tool(
        name="list_topics",
        description="Lists the topics of a course that the user can view. Returns topics plus `nextPageToken` for paging.",
        annotations=ToolAnnotations(readOnlyHint=True, openWorldHint=True),
    )
    def list_topics(
        course_id: str = Field(description="Identifier of the course. This identifier can be either the Classroom-assigned identifier or an alias."),
        page_size: int | None = Field(default=None, description="Maximum number of items to return. Zero or unspecified indicates that the server may assign a maximum. The server may return fewer than the specified number of results."),
        page_token: str | None = Field(default=None, description="nextPageToken value returned from a previous list call, indicating that the subsequent page of results should be returned. The list request must be otherwise identical to the one that resulted in this token."),
    ) -> ListTopicsResult:
        tlog = ToolLogger(logger, "list_topics")
        if not course_id.strip():
            return _err(ListTopicsResult, tlog, "VALIDATION_ERROR", "course_id must not be empty", 400)
        try:
            query = {k: v for k, v in {"pageSize": page_size, "pageToken": page_token}.items() if v is not None}
            data, status, retry_after = service.execute(lambda s: s.courses().topics().list(courseId=course_id, **query))
            if 200 <= status < 300:
                tlog.success()
                return ListTopicsResult(success=True, statusCode=status, data=ListTopicsData(**data))
            return _upstream_err(ListTopicsResult, tlog, status, data, retry_after)
        except Exception as exc:
            return _handle_request_exc(ListTopicsResult, tlog, exc)

    @mcp.tool(
        name="update_topic",
        description=(
            "Updates the provided fields of a topic (its name) and returns the updated topic. NOTE: this "
            "overwrites the current field values — the original state is not stored by the API after the call. "
            "The response includes both the before and after state so you have a full record of what changed."
        ),
        annotations=ToolAnnotations(readOnlyHint=False, destructiveHint=False, openWorldHint=True),
    )
    def update_topic(
        course_id: str = Field(description="Identifier of the course. This identifier can be either the Classroom-assigned identifier or an alias."),
        topic_id: str = Field(description="Identifier of the topic."),
        name: str | None = Field(default=None, description="The name of the topic, generated by the user. Leading and trailing whitespaces, if any, are trimmed. Also, multiple consecutive whitespaces are collapsed into one inside the name. The result must be a non-empty string. Topic names are case sensitive, and must be no longer than 100 characters."),
        update_mask: str | None = Field(default=None, description="Comma-separated field mask of the fields to update. Omit to update exactly the fields you provide."),
    ) -> UpdateTopicResult:
        tlog = ToolLogger(logger, "update_topic")
        if not course_id.strip():
            return _err(UpdateTopicResult, tlog, "VALIDATION_ERROR", "course_id must not be empty", 400)
        if not topic_id.strip():
            return _err(UpdateTopicResult, tlog, "VALIDATION_ERROR", "topic_id must not be empty", 400)
        body = {k: v for k, v in {"name": name}.items() if v is not None}
        if not body:
            return _err(UpdateTopicResult, tlog, "VALIDATION_ERROR", "Provide at least one field to change", 400)
        try:
            before_data, status, retry_after = service.execute(lambda s: s.courses().topics().get(courseId=course_id, id=topic_id))
            if not 200 <= status < 300:
                return _upstream_err(UpdateTopicResult, tlog, status, before_data, retry_after)
            data, status, retry_after = service.execute(lambda s: s.courses().topics().patch(courseId=course_id, id=topic_id, updateMask=update_mask or ",".join(body), body=body))
            if 200 <= status < 300:
                tlog.success()
                return UpdateTopicResult(success=True, statusCode=status, data=UpdateTopicData(before=Topic(**before_data), after=Topic(**data)))
            return _upstream_err(UpdateTopicResult, tlog, status, data, retry_after)
        except Exception as exc:
            return _handle_request_exc(UpdateTopicResult, tlog, exc)
